package com.github.galpiii.galpi.domain.collection;

/**
 * 수집한 것을 분석 파이프라인에 넘기기 직전에 통과해야 하는 관문.
 *
 * <p>저장소 하나를 수집하는 데 몇 분이 걸린다. 시작할 때 유효했던 근거 — 작업이 살아 있다,
 * 사용자가 외부 전송에 동의했다 — 가 그사이 사라질 수 있고, 코드가 밖으로 나가기 전 마지막
 * 지점이 여기다.
 *
 * <p>수집은 <b>이유를 모른다.</b> 통과하지 못하면 관문이 던지는 예외가 그대로 올라가고, 그것을
 * 무엇으로 볼지는 호출자가 정한다 — 취소라면 조용히 접고, 동의가 사라진 것이라면 작업을 실패로
 * 끝내야 한다. 이 구분을 수집 쪽에 두면 수집이 분석 작업과 동의 정책을 알아야 한다.
 */
@FunctionalInterface
public interface HandoffGuard {

    /** 인계해도 되면 그냥 돌아온다. 아니면 이유를 담은 예외를 던진다. */
    void check();
}
